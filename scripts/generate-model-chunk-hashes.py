#!/usr/bin/env python3
"""Generate reviewed, compiled integrity pins only from whole-file SHA-256 pins.

No runtime trust cache is written. Every model byte is hashed again on each load.
Usage: python3 scripts/generate-model-chunk-hashes.py MODEL_DIRECTORY OUTPUT.rs
Run `cargo fmt --all` after generation.
"""
import hashlib
import pathlib
import sys

CHUNK_BYTES = 16 * 1024 * 1024
PINS = (
    ("REFERENCE", "ggml-large-v3-turbo-q5_0.bin", 574041195,
     "394221709cd5ad1f40c46e6031ca61bce88931e6e088c188294c6d5a55ffa7e2"),
    ("COEFFICIENTS", "weights.safetensors", 3235574296,
     "277a2661c6d85f7e620adad07f7fda78b052a5a66b2c16e9fb6ccb3ac134d042"),
)

def generate(directory):
    lines = ["// Generated by scripts/generate-model-chunk-hashes.py from whole-file pins.",
             "// Review this source with the generator; never learn pins at runtime.",
             "use super::Manifest;", ""]
    for name, file, size, expected in PINS:
        path = directory / file
        if path.stat().st_size != size:
            raise ValueError(f"{file}: size differs from immutable pin")
        whole = hashlib.sha256()
        chunks = []
        with path.open("rb") as stream:
            while data := stream.read(CHUNK_BYTES):
                whole.update(data)
                chunks.append(hashlib.sha256(data).digest())
        if whole.hexdigest() != expected:
            raise ValueError(f"{file}: whole-file SHA-256 differs from immutable pin")
        lines.extend([f"pub(super) const {name}: Manifest = Manifest {{",
                      f"    bytes: {size},", f'    sha256: "{expected}",',
                      f"    chunk_bytes: {CHUNK_BYTES},", "    digests: &["])
        for digest in chunks:
            lines.append("        [" + ", ".join(f"0x{x:02x}" for x in digest) + "],")
        lines.extend(["    ],", "};", ""])
    return "\n".join(lines)

if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    content = generate(pathlib.Path(sys.argv[1]))
    pathlib.Path(sys.argv[2]).write_text(content)
