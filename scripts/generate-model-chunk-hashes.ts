/** Compile chunk pins only after verifying the immutable whole-file identity. */
import { createHash } from "node:crypto";
import { open } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { check } from "./tooling/audio-data.ts";
import { writeNewBytes } from "./tooling/io.ts";
export const CHUNK_BYTES = 16 * 1024 * 1024;
const PINS = [
  {
    name: "REFERENCE",
    file: "ggml-large-v3-turbo-q5_0.bin",
    bytes: 574041195,
    sha256: "394221709cd5ad1f40c46e6031ca61bce88931e6e088c188294c6d5a55ffa7e2",
  },
  {
    name: "COEFFICIENTS",
    file: "weights.safetensors",
    bytes: 3235574296,
    sha256: "277a2661c6d85f7e620adad07f7fda78b052a5a66b2c16e9fb6ccb3ac134d042",
  },
] as const;
export async function chunkDigests(
  file: string,
  expected: { bytes: number; sha256: string },
  chunkBytes = CHUNK_BYTES,
): Promise<Buffer[]> {
  check(
    Number.isSafeInteger(chunkBytes) &&
      chunkBytes > 0 &&
      chunkBytes <= CHUNK_BYTES,
    "Invalid chunk size",
  );
  const source = await open(file, "r");
  try {
    const initial = await source.stat();
    check(
      initial.isFile() && initial.size === expected.bytes,
      "Pinned size differs",
    );
    const whole = createHash("sha256");
    const digests: Buffer[] = [];
    const buffer = Buffer.alloc(chunkBytes);
    let total = 0;
    for (;;) {
      let used = 0;
      while (used < buffer.length) {
        const { bytesRead } = await source.read(
          buffer,
          used,
          buffer.length - used,
          null,
        );
        if (bytesRead === 0) break;
        used += bytesRead;
      }
      if (used === 0) break;
      total += used;
      check(total <= expected.bytes, "Source grew");
      const chunk = buffer.subarray(0, used);
      whole.update(chunk);
      digests.push(createHash("sha256").update(chunk).digest());
    }
    check(
      total === expected.bytes && whole.digest("hex") === expected.sha256,
      "Pinned hash differs",
    );
    return digests;
  } finally {
    await source.close();
  }
}
export async function generate(directory: string): Promise<string> {
  const lines = [
    "// Generated by scripts/generate-model-chunk-hashes.ts from whole-file pins.",
    "// Review this source with the generator; never learn pins at runtime.",
    "use super::Manifest;",
    "",
  ];
  for (const pin of PINS) {
    const digests = await chunkDigests(path.join(directory, pin.file), pin);
    lines.push(
      `pub(super) const ${pin.name}: Manifest = Manifest {`,
      `    bytes: ${pin.bytes},`,
      `    sha256: "${pin.sha256}",`,
      `    chunk_bytes: ${CHUNK_BYTES},`,
      "    digests: &[",
    );
    for (const digest of digests)
      lines.push(
        "        [" +
          [...digest]
            .map((byte) => `0x${byte.toString(16).padStart(2, "0")}`)
            .join(", ") +
          "],",
      );
    lines.push("    ],", "};", "");
  }
  return lines.join("\n");
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const [directory, output, ...extra] = process.argv.slice(2);
  if (!directory || !output || extra.length) {
    console.error(
      "Usage: generate-model-chunk-hashes.ts MODEL_DIRECTORY NEW_OUTPUT.rs",
    );
    process.exitCode = 2;
  } else
    generate(directory)
      .then((content) => writeNewBytes(output, content))
      .catch(() => {
        console.error("Model pin generation failed; output was not replaced");
        process.exitCode = 2;
      });
}
