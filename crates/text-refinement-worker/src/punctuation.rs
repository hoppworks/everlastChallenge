//! Fixed-word grammar and independently validated punctuation proposals.
use dictation_core::refinement::{Language, OriginalTranscript, ProposedEdit, propose_punctuation};
use text_refinement_protocol::FailureKind;

pub struct Plan {
    original: OriginalTranscript,
    pattern: String,
}
fn escape(value: &str) -> String {
    let mut escaped = String::new();
    for c in value.chars() {
        if ".+*?^$()[]{}|\\".contains(c) {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}
impl Plan {
    pub fn new(original: OriginalTranscript) -> Result<Self, FailureKind> {
        let text = original.as_str();
        let mut ranges = Vec::new();
        let mut start = None;
        for (index, c) in text
            .char_indices()
            .chain(std::iter::once((text.len(), ' ')))
        {
            if c.is_whitespace() {
                if let Some(start) = start.take() {
                    ranges.push(start..index);
                }
            } else {
                start.get_or_insert(index);
            }
        }
        if ranges.len() > 8192 {
            return Err(FailureKind::InputLimit);
        }
        let mut pattern = String::from("^");
        let mut cursor = 0;
        for (index, range) in ranges.iter().enumerate() {
            pattern.push_str(&escape(&text[cursor..range.start]));
            let word = &text[range.clone()];
            let mut chars = word.chars();
            let first = chars.next().ok_or(FailureKind::InvalidCandidate)?;
            let title = if first.is_lowercase() && !chars.clone().any(char::is_uppercase) {
                first.to_uppercase().collect::<String>() + chars.as_str()
            } else {
                word.into()
            };
            if title == word {
                pattern.push_str(&escape(word));
            } else {
                pattern.push_str(&format!("(?:{}|{})", escape(word), escape(&title)));
            }
            cursor = range.end;
            let next = ranges.get(index + 1).map_or(text.len(), |r| r.start);
            let gap = &text[cursor..next];
            if index + 1 < ranges.len()
                && gap == " "
                && !word.ends_with([',', '.', '!', '?', ':', ';'])
            {
                pattern.push_str("[,.!?:;]? ");
                cursor = next;
            }
        }
        if let Some(last) = ranges.last()
            && !text[last.clone()].ends_with(['.', '!', '?'])
        {
            pattern.push_str("[.!?]?");
        }
        pattern.push_str(&escape(&text[cursor..]));
        pattern.push('$');
        if pattern.len() > 512 * 1024 {
            return Err(FailureKind::InputLimit);
        }
        Ok(Self { original, pattern })
    }
    pub fn schema(&self) -> serde_json::Value {
        // The anchored pattern already bounds every word, gap and punctuation
        // choice. Intersecting it with a second maxLength automaton makes long
        // valid transcripts exceed the grammar compiler's complexity budget.
        // Input, pattern, generated bytes/tokens and deadline remain bounded;
        // decode independently checks the result before it can leave the worker.
        serde_json::json!({"type":"object","properties":{"text":{"type":"string","pattern":self.pattern}},"required":["text"],"additionalProperties":false})
    }
    pub fn decode(
        &self,
        output: &str,
        language: Language,
    ) -> Result<Vec<ProposedEdit>, FailureKind> {
        if output.len() > 64 * 1024 {
            return Err(FailureKind::InputLimit);
        }
        #[derive(serde::Deserialize)]
        #[serde(deny_unknown_fields)]
        struct Output {
            text: String,
        }
        let output: Output =
            serde_json::from_str(output).map_err(|_| FailureKind::InvalidCandidate)?;
        propose_punctuation(&self.original, &output.text, language)
            .map_err(|_| FailureKind::InvalidCandidate)
    }
}
